                throw new Exception(texto);
            return JsonConvert.DeserializeObject<Gerentes>(texto)!;
        }

        public async Task<List<Gerentes>> Consultar()
        {
            var cliente = new HttpClient();
            var contenido = new StringContent("{}", Encoding.UTF8, "application/json");
            var respuesta = await cliente.PostAsync(this.url + "Consultar", contenido);
            var texto = await respuesta.Content.ReadAsStringAsync();
            if (!respuesta.IsSuccessStatusCode)
                throw new Exception(texto);
            return JsonConvert.DeserializeObject<List<Gerentes>>(texto)!;
        }

        public async Task<List<Gerentes>> Buscar(Gerentes entidad)
        {
            var cliente = new HttpClient();
